// Distinguish maintainable production code from tests, generated and vendored code.
// A filename heuristic is a candidate, not proof of origin or Agent authorship.
import path from "node:path";
import { TEST_SCOPE_PATTERN } from "./constants.js";
import { rustTestRanges, locInRanges } from "./rust-test-scope.js";
import { swiftTestRanges } from "./swift-parse.js";

const GENERATED_DIR = /(^|\/)(generated|__generated__|gen|autogenerated|auto-generated)(\/|$)/i;
const VENDOR_DIR = /(^|\/)(vendor|third_party|third-party|external|node_modules)(\/|$)/i;
const TOOLING_DIR = /^(scripts?|docs?|fixtures?|benchmarks?|examples?|dev)(\/|$)/i;
const GENERATED_NAME = /(?:\.generated\.[^.]+$|(?:^|\/)[^/]+(?:\.g\.dart|_generated\.py|_pb2(?:_grpc)?\.py)$)/i;
const GENERATED_HEADER = /(?:^|\n)\s*(?:\/\/|#|\/\*)\s*(?:code generated\b|@generated\b|auto-generated\b|this file is generated\b)[^\n]{0,120}/i;

export function classifySourceScope(filePath, source = "") {
  const rel = String(filePath).replaceAll("\\", "/");
  const base = path.posix.basename(rel);
  if (VENDOR_DIR.test(rel)) return { kind: "vendor", reason: "vendor_path" };
  if (GENERATED_DIR.test(rel) || GENERATED_NAME.test(rel) || GENERATED_HEADER.test(source.slice(0, 1500)))
    return { kind: "generated", reason: "generated_path_or_header" };
  if (TEST_SCOPE_PATTERN.test(rel) || /(?:^|\/)(?:[^/]+Tests?\.swift|tests?\.rs)$/i.test(rel))
    return { kind: "test", reason: "test_path_or_suffix" };
  // Rust inline tests are mixed source: never silently exclude the production code.
  if (base.endsWith(".rs") && /#\s*\[\s*cfg\s*\(\s*test\s*\)\s*\]/.test(source)) {
    const parsed=rustTestRanges(source);
    if (parsed.ranges.length) return {
      kind: "mixed", reason: "rust_inline_cfg_test",
      testRanges: parsed.ranges,
      testLoc: locInRanges(source,parsed.ranges),
      parserErrors: parsed.parseErrors
    };
  }
  if(base.endsWith(".swift") && /@Test\b|XCTestCase\b/.test(source)){
    const parsed=swiftTestRanges(source);
    if(parsed.ranges.length)return {kind:"mixed",reason:"swift_inline_test",
      testRanges:parsed.ranges,testLoc:parsed.testLoc,parserErrors:parsed.parserErrors};
  }
  if (TOOLING_DIR.test(rel)) return { kind: "tooling", reason: "tooling_path" };
  return { kind: "production", reason: "source_path" };
}

export function repairPythonImportReachability(files) {
  let corrected = 0;
  for (let pass = 0; pass < 3; pass++) {
    let changed = 0;
    for (const file of files) {
      const name = path.posix.basename(file.path);
      if (!/^test_[a-z0-9_]+\.py$/i.test(name) || !file.isTestFile ||
          /(^|\/)(tests?|__tests__|specs?|fixtures?)(\/|$)/i.test(file.path)) continue;
      const modulePath = file.path.replace(/\.py$/i, "").replaceAll("/", ".");
      const shortName = name.slice(0, -3);
      const importer = files.find(other => other !== file &&
        !other.isTestFile && !other.isToolingFile &&
        !["vendor", "generated"].includes(other.sourceScope?.kind) &&
        (other.imports || []).some(spec =>
          spec === modulePath || spec === shortName ||
          (modulePath.endsWith("." + spec) && spec.includes("."))));
      if (importer) {
        file.sourceScope = { kind: "production", reason: "imported_from_production", importer: importer.path };
        file.isTestFile = false;
        file.productionLoc = file.loc;
        file.testLoc = 0;
        file.assertionSignals = 0;
        corrected++;
        changed++;
      }
    }
    if (!changed) break;
  }
  return corrected;
}
