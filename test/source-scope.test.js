import test from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { classifySourceScope } from "../src/source-scope.js";
import { scanProject } from "../src/scanner.js";

test("source scope: audited languages, generated/vendored and negative controls", () => {
  const cases = [
    ["cli/deploy_test.go", "", "test"],
    ["pkg/test_helper.go", "", "production"],
    ["Tests/MyFeatureTests.swift", "", "test"],
    ["run/tests.rs", "", "test"],
    ["src/service.rs", "#[cfg(test)] mod tests {} \n pub fn run() {}", "mixed"],
    ["src/test_harvest.py", "", "test"],
    ["src/generated/wire.ts", "", "generated"],
    ["pkg/vendor/client.py", "", "vendor"],
    ["src/generated-client.ts", "// @generated\nexport function api(){}", "generated"],
    ["src/service.ts", "", "production"]
  ];
  for (const [p, source, expected] of cases)
    assert.equal(classifySourceScope(p, source).kind, expected, p);
});

test("scanner reclassifies import-reachable Python test_* production modules; keeps true tests", () => {
  const dir=fs.mkdtempSync(path.join(os.tmpdir(),"vm-scope-py-"));
  try {
    for(const [p, body] of Object.entries({
      "agent/main.py":"from agent.test_harvest import run\nrun()\n",
      "agent/test_harvest.py":"def run():\n return 42\n",
      "tests/test_harvest.py":"from agent.test_harvest import run\nassert run() == 42\n",
      "tests/basic_test.go":"func TestBasic() {}\n",
      "generated/autocode.py":"# Code generated by tool. DO NOT EDIT\npass\n",
      "src/extra.rs":"fn run(){}\n#[cfg(test)] mod tests {}\n"
    })){
      const target=path.join(dir,p);fs.mkdirSync(path.dirname(target),{recursive:true});fs.writeFileSync(target,body);
    }
    const scan=scanProject(dir, {limits:{maxElapsedMs:10000}});
    const find=p=>scan.files.find(f=>f.path===p);
    assert.equal(find("agent/test_harvest.py").isTestFile,false);
    assert.equal(find("agent/test_harvest.py").sourceScope.reason,"imported_from_production");
    assert.equal(find("tests/test_harvest.py").isTestFile,true);
    assert.equal(find("tests/basic_test.go").isTestFile,true);
    assert.equal(find("generated/autocode.py").sourceScope.kind,"generated");
    assert.equal(find("src/extra.rs").sourceScope.kind,"mixed");
    assert.equal(scan.summary?.scopeCoverage?.production?.files >= 2,true);
  }finally{fs.rmSync(dir,{recursive:true,force:true});}
});
